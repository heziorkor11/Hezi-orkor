const aliasIndex = new Map<string, string>();
for (const [raw, value] of Object.entries(MOT_MODEL_ALIASES)) {
  const key = normalizeKey(raw);
  if (key && !aliasIndex.has(key)) aliasIndex.set(key, value);
  const compact = key.replace(/\s+/g, "");
  if (compact && !aliasIndex.has(compact)) aliasIndex.set(compact, value);
}

const ambiguousIndex = new Set<string>();
for (const raw of MOT_AMBIGUOUS_MODEL_KEYS) {
  const key = normalizeKey(raw);
  if (key) ambiguousIndex.add(key);
  const compact = key.replace(/\s+/g, "");
  if (compact) ambiguousIndex.add(compact);
}

export function lookupMotModelAlias(raw: string): string | undefined {
  const key = normalizeKey(raw);
  if (!key) return undefined;
  return aliasIndex.get(key) || aliasIndex.get(key.replace(/\s+/g, ""));
}

export function isAmbiguousMotModelKey(raw: string) {
  const key = normalizeKey(raw);
  if (!key) return false;
  return ambiguousIndex.has(key) || ambiguousIndex.has(key.replace(/\s+/g, ""));
}
